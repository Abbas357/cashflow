"""Writes lib/core/utils/zone_countries.dart from the IANA time zone database.

    python -m pip install tzdata
    python tool/make_zone_countries.py

Run it again only to pick up a newer tzdata. zone.tab gives each zone's
country; the links in tzdata.zi add old names browsers still report, such as
Asia/Calcutta. A zone used by several countries gets its first one in zone.tab.
"""
import os

import tzdata

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ZONEINFO = os.path.join(os.path.dirname(tzdata.__file__), "zoneinfo")

countries = {}
with open(os.path.join(ZONEINFO, "zone.tab"), encoding="utf-8") as f:
    for line in f:
        if line.startswith("#") or not line.strip():
            continue
        country, _, zone = line.rstrip("\n").split("\t")[:3]
        countries.setdefault(zone, country)

links = []
with open(os.path.join(ZONEINFO, "tzdata.zi"), encoding="utf-8") as f:
    for line in f:
        if line.startswith("L "):
            _, target, alias = line.split()
            links.append((target, alias))

# Links can point at other links, so go round until nothing new turns up.
changed = True
while changed:
    changed = False
    for target, alias in links:
        if alias not in countries and target in countries:
            countries[alias] = countries[target]
            changed = True

out = os.path.normpath(os.path.join(ROOT, "lib", "core", "utils", "zone_countries.dart"))
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tool/make_zone_countries.py from the IANA time zone database.\n")
    f.write("// Do not edit by hand.\n\n")
    f.write("/// The ISO country code for each IANA time zone name.\n")
    f.write("const zoneCountries = <String, String>{\n")
    for zone in sorted(countries):
        f.write(f"  '{zone}': '{countries[zone]}',\n")
    f.write("};\n")
print(f"{len(countries)} zones written to {out}")
