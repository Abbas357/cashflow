// Writes web/privacy/index.html from lib/core/legal/privacy_policy.dart:
//
//   dart run tool/make_privacy_html.dart
import 'dart:io';

import 'package:cash_flow/core/legal/privacy_policy.dart';

String _escape(String s) => s.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');

/// Plain text with its web and email addresses made into links.
String _text(String s) => _escape(s).replaceAllMapped(
  RegExp(r'https://[^\s]*[^\s.,]|[\w.]+@[\w.]*\w'),
  (m) => '<a href="${m[0]!.startsWith('http') ? '' : 'mailto:'}${m[0]}">${m[0]}</a>',
);

String privacyHtml() {
  final b = StringBuffer();
  for (final s in privacySections) {
    b.writeln('    <section>');
    b.writeln('      <h2>${_text(s.title)}</h2>');
    if (s.intro != null) b.writeln('      <p>${_text(s.intro!)}</p>');
    if (s.bullets.isNotEmpty) {
      b.writeln('      <ul>');
      for (final item in s.bullets) {
        b.writeln('        <li>${_text(item)}</li>');
      }
      b.writeln('      </ul>');
    }
    if (s.outro != null) b.writeln('      <p>${_text(s.outro!)}</p>');
    b.writeln('    </section>');
  }
  return '''
<!DOCTYPE html>
<!--
  Generated by tool/make_privacy_html.dart from lib/core/legal/privacy_policy.dart.
  Do not edit by hand. Give this address in Play Console, under App content,
  Privacy policy: $privacyUrl

  Plain HTML on purpose, like ../delete-account/: it answers 200 and can be read
  anywhere, with no app and no script.
-->
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="What the Cash Flow app collects, why, how long it is kept and how to delete it.">
  <title>Cash Flow privacy policy</title>
  <link rel="icon" type="image/png" href="../favicon.png">
  <style>
    :root {
      --bg: #F4F6F5; --card: #FFFFFF; --text: #1A1F1C; --muted: #5C6661;
      --line: #DCE5E0; --brand: #006B3C;
    }
    @media (prefers-color-scheme: dark) {
      :root {
        --bg: #0F1412; --card: #1A211D; --text: #E7ECE9; --muted: #A0ABA5;
        --line: #26302B; --brand: #3DCB86;
      }
    }
    * { box-sizing: border-box; }
    body {
      margin: 0; padding: 32px 16px 48px; background: var(--bg); color: var(--text);
      font: 16px/1.55 system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
    }
    main { max-width: 680px; margin: 0 auto; }
    header { display: flex; align-items: center; gap: 14px; margin-bottom: 20px; }
    header img { width: 56px; height: 56px; border-radius: 14px; }
    header p { margin: 0; color: var(--muted); }
    h1 { margin: 0; font-size: 26px; line-height: 1.25; }
    h2 { margin: 0 0 8px; font-size: 18px; color: var(--brand); }
    a { color: var(--brand); overflow-wrap: anywhere; }
    section {
      background: var(--card); border: 1px solid var(--line); border-radius: 12px;
      padding: 18px 20px; margin-top: 14px;
    }
    ul { margin: 0; padding-left: 22px; }
    li { margin-bottom: 6px; }
    li:last-child { margin-bottom: 0; }
    section p { margin: 0; }
    p + ul, ul + p { margin-top: 10px; }
    .intro { margin: 0; }
  </style>
</head>
<body>
  <main>
    <header>
      <img src="../icons/Icon-192.png" alt="">
      <div>
        <h1>Cash Flow privacy policy</h1>
        <p>Last updated $privacyUpdated</p>
      </div>
    </header>
    <p class="intro">${_text(privacyIntro)}</p>

$b  </main>
</body>
</html>
''';
}

void main() {
  File('web/privacy/index.html')
    ..createSync(recursive: true)
    ..writeAsStringSync(privacyHtml());
  stdout.writeln('Wrote web/privacy/index.html');
}
